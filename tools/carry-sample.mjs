#!/usr/bin/env node
/**
 * carry-sample — ship the example data with the page.
 *
 *   node tools/carry-sample.mjs [<path to fixtures/sample.md>]
 *
 * "Skip upload, show example data" builds its demo from Sam, the made-up sample person in Marketing/Beta Signups/fixtures/sample.md. The page used to fetch a copy of that file, and on a protected Vercel preview the fetch was answered with a sign-in redirect, so the example said the file couldn't be opened (27 Oct 2026). Now the file's text is written into workspace/try/sample-data.js, a module the page imports, so the example needs no request at all. Run this again when the fixture changes, and commit the result; tools/check-invite.mjs fails if the two differ.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const from = process.argv[2] ?? '/Users/brian/Syncthing/Projects/Agentic Workspace/Marketing/Beta Signups/fixtures/sample.md';
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'workspace', 'try', 'sample-data.js');
const text = readFileSync(from, 'utf8');

writeFileSync(out, `/* Generated by tools/carry-sample.mjs from Marketing/Beta Signups/fixtures/sample.md on ${new Date().toISOString().slice(0, 10)}: the example data's file, shipped with the page so showing it needs no request. Sam is made up. Do not edit; change the fixture and run the script again. */\nexport const SAMPLE_TEXT = ${JSON.stringify(text)};\n`);
console.log(`wrote ${out}: ${text.length} characters`);

#!/usr/bin/env node
/**
 * carry-prompt — ship the page's version of the agent prompt with the page, for "Get my file" (M-017).
 *
 *   node tools/carry-prompt.mjs [<path to Marketing/Beta Signups/Prompt.md>]
 *
 * Reads the text between `<!-- page prompt starts -->` and `<!-- page prompt ends -->` in Prompt.md, the version MC: Invite wrote for the page, and writes it into workspace/try/prompt-data.js, so copying it needs no request. Run this again when Prompt.md changes, and commit the result; tools/check-invite.mjs fails if the two differ.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const from = process.argv[2] ?? '/Users/brian/Syncthing/Projects/Agentic Workspace/Marketing/Beta Signups/Prompt.md';
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'workspace', 'try', 'prompt-data.js');

export function pagePrompt(markdown) {
  const m = markdown.match(/<!-- page prompt starts -->\n([\s\S]*?)\n<!-- page prompt ends -->/);
  if (!m) throw new Error('no "page prompt" markers in Prompt.md');
  return m[1].trim() + '\n';
}

// Run directly (not imported by the check): compare paths, since the URL encodes spaces.
if (fileURLToPath(import.meta.url) === resolve(process.argv[1] ?? '')) {
  const text = pagePrompt(readFileSync(from, 'utf8'));
  writeFileSync(out, `/* Generated by tools/carry-prompt.mjs from Marketing/Beta Signups/Prompt.md ("The page's version") on ${new Date().toISOString().slice(0, 10)}. Do not edit; change Prompt.md and run the script again. */\nexport const PAGE_PROMPT = ${JSON.stringify(text)};\n`);
  console.log(`wrote ${out}: ${text.length} characters`);
}
